let marks = 85

if marks < 0 || marks > 100 {
    print("Invalid Marks")
} else if marks >= 90 {
    print("Grade A")
} else if marks >= 80 {
    print("Grade B")
} else if marks >= 70 {
    print("Grade C")
} else if marks >= 60 {
    print("Grade D")
} else if marks >= 50 {
    print("Grade E")
} else {
    print("Fail")
}